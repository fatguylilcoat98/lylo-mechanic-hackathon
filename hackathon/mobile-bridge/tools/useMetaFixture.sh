#!/usr/bin/env bash
# v0.7.7: wire a REAL recorded Meta AI answer into tour 12. Usage: tools/useMetaFixture.sh /workspace/out/meta-real-answer-XXXX.json
set -euo pipefail
F="$1"; D="$(cd "$(dirname "$0")/.." && pwd)/src/tourData"
python3 -c "import json,sys; json.load(open(sys.argv[1]))" "$F"
cp "$F" "$D/meta_real.json"
printf "/* GENERATED by tools/useMetaFixture.sh from %s (sha256 %s). Real recorded Meta AI answer. */\nmodule.exports = require('./meta_real.json');\n" "$(basename "$F")" "$(sha256sum "$F" | cut -c1-64)" > "$D/metaReal.js"
echo "wired $(basename "$F")"
